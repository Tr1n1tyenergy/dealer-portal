import PDFDocument from "pdfkit";
import { formatStockReportDate } from "./dates";
import { formatKesWithCurrency, formatKesFixed } from "./monetary-calc";
import { formatLitresWithUnit } from "./pump-calc";
import { wetResolutionLabel } from "./reference";

export type StockSaleReportPdfData = {
  reportReference: string;
  stationName: string;
  reportingDate: Date;
  closedAt: Date | null;
  meterPms: number;
  meterAgo: number;
  tankPms: number;
  tankAgo: number;
  varianceTotal: number | null;
  wetResolution: string;
  wetState: string;
  pricePms: number | null;
  priceAgo: number | null;
  expectedPms: number | null;
  expectedAgo: number | null;
  expectedTotal: number | null;
  cash: number | null;
  mpesa: number | null;
  card: number | null;
  collectionsTotal: number | null;
  monetaryDifference: number | null;
  monetaryState: string;
  discrepancyReason: string | null;
  wetLossReason: string | null;
};

function money(v: number | null | undefined) {
  return v == null ? "—" : formatKesWithCurrency(v);
}

function litres(v: number | null | undefined) {
  return v == null ? "—" : formatLitresWithUnit(v);
}

/** Server-side PDF for a closed stock sale report (pdfkit, same stack as PFI). */
export function renderStockSaleReportPdf(data: StockSaleReportPdfData): Promise<Buffer> {
  const doc = new PDFDocument({
    size: "A4",
    margin: 48,
    info: {
      Title: `Stock Sale Report ${data.reportReference}`,
      Author: "Trinity Retail Intelligence",
    },
  });
  const chunks: Buffer[] = [];
  doc.on("data", (chunk: Buffer) => chunks.push(chunk));
  const done = new Promise<Buffer>((resolve, reject) => {
    doc.on("end", () => resolve(Buffer.concat(chunks)));
    doc.on("error", reject);
  });

  const blue = "#3551A5";
  const ink = "#0a235b";

  doc.fillColor(blue).fontSize(16).text("Trinitynrg", { continued: false });
  doc.fillColor(ink).fontSize(18).text("Daily Stock Sale Report", { continued: false });
  doc.moveDown(0.4);
  doc.fontSize(10).fillColor("#64748b").text(`Reference: ${data.reportReference}`);
  doc.text(`Station: ${data.stationName}`);
  doc.text(`Reporting date: ${formatStockReportDate(data.reportingDate)}`);
  if (data.closedAt) {
    doc.text(
      `Submitted: ${data.closedAt.toLocaleString("en-GB", {
        timeZone: "Africa/Nairobi",
        day: "2-digit",
        month: "short",
        year: "numeric",
        hour: "2-digit",
        minute: "2-digit",
        hour12: false,
      })}`
    );
  }
  doc.text("Status: Closed");
  doc.moveDown();

  doc.fillColor(blue).fontSize(12).text("Meter Sales (Dispensers)");
  doc.fillColor(ink).fontSize(10);
  doc.text(`PMS: ${litres(data.meterPms)}`);
  doc.text(`AGO: ${litres(data.meterAgo)}`);
  doc.text(`Total: ${litres((data.meterPms ?? 0) + (data.meterAgo ?? 0))}`);
  doc.moveDown(0.6);

  doc.fillColor(blue).fontSize(12).text("Tank Stock Sales (Dips)");
  doc.fillColor(ink).fontSize(10);
  doc.text(`PMS: ${litres(data.tankPms)}`);
  doc.text(`AGO: ${litres(data.tankAgo)}`);
  doc.text(`Total: ${litres((data.tankPms ?? 0) + (data.tankAgo ?? 0))}`);
  doc.moveDown(0.6);

  doc.fillColor(blue).fontSize(12).text("Wet Stock Reconciliation");
  doc.fillColor(ink).fontSize(10);
  doc.text(`Variance (Meter − Tank): ${litres(data.varianceTotal)}`);
  doc.text(`Resolution: ${wetResolutionLabel(data.wetResolution, data.wetState)}`);
  if (data.wetLossReason) doc.text(`Loss note: ${data.wetLossReason}`);
  doc.moveDown(0.6);

  doc.fillColor(blue).fontSize(12).text("Expected Revenue");
  doc.fillColor(ink).fontSize(10);
  doc.text(
    `PMS (${litres(data.meterPms)} × KES ${data.pricePms == null ? "—" : formatKesFixed(data.pricePms)}): ${money(data.expectedPms)}`
  );
  doc.text(
    `AGO (${litres(data.meterAgo)} × KES ${data.priceAgo == null ? "—" : formatKesFixed(data.priceAgo)}): ${money(data.expectedAgo)}`
  );
  doc.text(`Total Expected Sales: ${money(data.expectedTotal)}`);
  doc.moveDown(0.6);

  doc.fillColor(blue).fontSize(12).text("Actual Collections");
  doc.fillColor(ink).fontSize(10);
  doc.text(`Cash: ${money(data.cash)}`);
  doc.text(`M-Pesa: ${money(data.mpesa)}`);
  doc.text(`Visa / Card: ${money(data.card)}`);
  doc.text(`Total Collections: ${money(data.collectionsTotal)}`);
  doc.moveDown(0.6);

  doc.fillColor(blue).fontSize(12).text("Monetary Reconciliation");
  doc.fillColor(ink).fontSize(10);
  doc.text(`State: ${data.monetaryState}`);
  doc.text(`Difference: ${money(data.monetaryDifference)}`);
  if (data.discrepancyReason) doc.text(`Discrepancy note: ${data.discrepancyReason}`);

  doc.moveDown(1.2);
  doc.fontSize(8).fillColor("#94a3b8").text("Generated by Trinity Retail Intelligence — Dealer Portal");

  doc.end();
  return done;
}
